/**
 * DataSpeak — Chart Viewer Component (ChartViewer.tsx)
 * Calm Analytics Workspace (docs/ui-example/code1.html & DESIGN.md)
 * High-contrast data visualization:
 * Bar, Line, and Donut/Pie charts with segmented type switch,
 * series palette (#0075de, #f7a501, #2a9d99, #7c44a6, #62aef0),
 * dashed grid lines, and PostHog dark tooltips (#23251d).
 */

import React, { useState } from 'react';
import {
  ResponsiveContainer,
  BarChart,
  Bar,
  LineChart,
  Line,
  PieChart,
  Pie,
  Cell,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
} from 'recharts';
import type { ChartConfig, ChartType } from '../../types';

interface ChartViewerProps {
  config?: ChartConfig;
  rows: Record<string, unknown>[];
  columns: string[];
  title?: string;
  subtitle?: string;
}

// Calm Analytics Workspace series colors (Strictly NO green/red; those mean safety)
const CALM_CHART_SERIES = [
  '#0075de', // Series 1 - Primary Blue
  '#f7a501', // Series 2 - Amber
  '#2a9d99', // Series 3 - Teal
  '#7c44a6', // Series 4 - Purple
  '#62aef0', // Series 5 - Sky Blue
  '#d6409f', // Series 6 - Magenta
];

export const ChartViewer: React.FC<ChartViewerProps> = ({
  config,
  rows,
  columns,
  title,
  subtitle,
}) => {
  const initialType: ChartType =
    config?.type && config.type !== 'none' ? config.type : 'bar';

  const [activeChartType, setActiveChartType] = useState<ChartType>(initialType);

  const xKey =
    config?.x_key ||
    config?.xKey ||
    columns.find((c) => {
      const name = c.toLowerCase();
      return (
        name.includes('month') ||
        name.includes('date') ||
        name.includes('name') ||
        name.includes('plan') ||
        name.includes('tier') ||
        name.includes('category') ||
        name.includes('title')
      );
    }) ||
    columns[0] ||
    'name';

  const yKey =
    config?.y_key ||
    config?.yKey ||
    columns.find((c) => {
      const name = c.toLowerCase();
      return (
        name !== xKey &&
        (name.includes('mrr') ||
          name.includes('revenue') ||
          name.includes('subscribers') ||
          name.includes('total') ||
          name.includes('amount') ||
          name.includes('count') ||
          name.includes('price'))
      );
    }) ||
    columns[1] ||
    'value';

  if (!rows || rows.length === 0 || columns.length < 2) {
    return null;
  }

  // Format chart data (top 24 rows)
  const chartData = rows.slice(0, 24).map((row) => ({
    ...row,
    [xKey]: String(row[xKey] ?? 'Unknown'),
    [yKey]: typeof row[yKey] === 'number' ? row[yKey] : Number(row[yKey]) || 0,
  }));

  // Detect distinct categories / plans if multiple series exist
  const displayTitle = title || config?.title || `${yKey.replace(/_/g, ' ').toUpperCase()} by ${xKey.replace(/_/g, ' ')}`;
  const displaySubtitle = subtitle || 'Visual representation generated by DataSpeak AI';

  // Custom Dark Tooltip (#23251d)
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const renderCustomTooltip = (props: any) => {
    const { active, payload, label } = props;
    if (active && payload && payload.length) {
      return (
        <div className="rounded-md bg-[#23251d] text-white p-3 shadow-lg border border-white/10 text-[12px] font-sans">
          <p className="font-semibold text-neutral-200 mb-1">{label}</p>
          {/* eslint-disable-next-line @typescript-eslint/no-explicit-any */}
          {payload.map((entry: any, index: number) => (
            <p key={`item-${index}`} className="flex items-center gap-2 tnum">
              <span
                className="h-2 w-2 rounded-xs"
                style={{ backgroundColor: entry.color || CALM_CHART_SERIES[0] }}
              />
              <span className="text-neutral-400 capitalize">{entry.name}:</span>
              <span className="font-semibold text-white">
                {typeof entry.value === 'number'
                  ? entry.value.toLocaleString(undefined, { maximumFractionDigits: 2 })
                  : String(entry.value)}
              </span>
            </p>
          ))}
        </div>
      );
    }
    return null;
  };

  return (
    <div className="bg-white rounded-lg p-5 sm:p-6 border border-[#e6e6e6] shadow-2xs flex flex-col gap-6">
      {/* Header & Segmented Control */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h2 className="text-[18px] font-semibold tracking-[-0.2px] text-[#0d0d0d] capitalize">
            {displayTitle}
          </h2>
          <p className="text-[13px] text-[#615d59]">{displaySubtitle}</p>
        </div>

        {/* Segmented Control (Bar / Line / Pie) */}
        <div className="flex items-center bg-[#efeeec] p-1 rounded-md self-start sm:self-auto border border-[#e6e6e6]">
          <button
            type="button"
            onClick={() => setActiveChartType('bar')}
            className={`px-3 py-1 text-[13px] font-medium rounded-sm transition-all cursor-pointer ${
              activeChartType === 'bar'
                ? 'bg-white text-[#0d0d0d] shadow-2xs border border-[#e6e6e6]'
                : 'text-[#615d59] hover:text-[#0d0d0d]'
            }`}
          >
            Bar
          </button>
          <button
            type="button"
            onClick={() => setActiveChartType('line')}
            className={`px-3 py-1 text-[13px] font-medium rounded-sm transition-all cursor-pointer ${
              activeChartType === 'line'
                ? 'bg-white text-[#0d0d0d] shadow-2xs border border-[#e6e6e6]'
                : 'text-[#615d59] hover:text-[#0d0d0d]'
            }`}
          >
            Line
          </button>
          <button
            type="button"
            onClick={() => setActiveChartType('pie')}
            className={`px-3 py-1 text-[13px] font-medium rounded-sm transition-all cursor-pointer ${
              activeChartType === 'pie'
                ? 'bg-white text-[#0d0d0d] shadow-2xs border border-[#e6e6e6]'
                : 'text-[#615d59] hover:text-[#0d0d0d]'
            }`}
          >
            Pie
          </button>
        </div>
      </div>

      {/* Series Legend (Calm Palette: Blue, Amber, Teal, Purple) */}
      <div className="flex items-center flex-wrap gap-5 text-[12px] text-[#31302e]">
        <div className="flex items-center gap-1.5">
          <span className="w-2.5 h-2.5 rounded-xs bg-[#0075de]"></span>
          <span className="font-medium capitalize">{yKey.replace(/_/g, ' ')} (Primary)</span>
        </div>
        {activeChartType === 'pie' &&
          chartData.slice(0, 4).map((entry, idx) => (
            <div key={idx} className="flex items-center gap-1.5">
              <span
                className="w-2.5 h-2.5 rounded-xs"
                style={{ backgroundColor: CALM_CHART_SERIES[idx % CALM_CHART_SERIES.length] }}
              ></span>
              <span className="font-medium">{String(entry[xKey])}</span>
            </div>
          ))}
      </div>

      {/* Chart Canvas */}
      <div className="w-full h-72">
        <ResponsiveContainer width="100%" height="100%">
          {activeChartType === 'bar' ? (
            <BarChart data={chartData} margin={{ top: 10, right: 10, left: -10, bottom: 20 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="#e6e6e6" vertical={false} />
              <XAxis
                dataKey={xKey}
                stroke="#615d59"
                fontSize={12}
                tickLine={false}
                axisLine={{ stroke: '#dddddd' }}
                dy={6}
              />
              <YAxis
                stroke="#615d59"
                fontSize={12}
                tickLine={false}
                axisLine={false}
                tickFormatter={(val) =>
                  typeof val === 'number' && val >= 1000 ? `$${(val / 1000).toFixed(0)}k` : val
                }
              />
              <Tooltip content={renderCustomTooltip} />
              <Bar
                dataKey={yKey}
                fill={CALM_CHART_SERIES[0]}
                radius={[4, 4, 0, 0]}
                maxBarSize={48}
              >
                {chartData.map((_, index) => (
                  <Cell
                    key={`cell-${index}`}
                    fill={CALM_CHART_SERIES[index % CALM_CHART_SERIES.length]}
                  />
                ))}
              </Bar>
            </BarChart>
          ) : activeChartType === 'line' ? (
            <LineChart data={chartData} margin={{ top: 10, right: 10, left: -10, bottom: 20 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="#e6e6e6" vertical={false} />
              <XAxis
                dataKey={xKey}
                stroke="#615d59"
                fontSize={12}
                tickLine={false}
                axisLine={{ stroke: '#dddddd' }}
                dy={6}
              />
              <YAxis
                stroke="#615d59"
                fontSize={12}
                tickLine={false}
                axisLine={false}
                tickFormatter={(val) =>
                  typeof val === 'number' && val >= 1000 ? `$${(val / 1000).toFixed(0)}k` : val
                }
              />
              <Tooltip content={renderCustomTooltip} />
              <Line
                type="monotone"
                dataKey={yKey}
                stroke={CALM_CHART_SERIES[0]}
                strokeWidth={2.5}
                dot={{ r: 4, fill: CALM_CHART_SERIES[0], strokeWidth: 1, stroke: '#ffffff' }}
                activeDot={{ r: 6, fill: CALM_CHART_SERIES[0] }}
              />
            </LineChart>
          ) : (
            <PieChart>
              <Tooltip content={renderCustomTooltip} />
              <Pie
                data={chartData.slice(0, 8)}
                dataKey={yKey}
                nameKey={xKey}
                cx="50%"
                cy="50%"
                innerRadius={60}
                outerRadius={95}
                paddingAngle={2}
              >
                {chartData.slice(0, 8).map((_, index) => (
                  <Cell
                    key={`cell-${index}`}
                    fill={CALM_CHART_SERIES[index % CALM_CHART_SERIES.length]}
                  />
                ))}
              </Pie>
            </PieChart>
          )}
        </ResponsiveContainer>
      </div>
    </div>
  );
};
